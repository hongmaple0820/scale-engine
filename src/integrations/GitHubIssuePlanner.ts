// SCALE Engine — P3-D GitHub tasks→issues planner
//
// 把 SCALE Task 映射为 GitHub issue 草稿（title/body/labels）。默认 dry-run：
// 只产出计划，不真正调用 GitHub API（发布是外部账号操作）。纯函数，可单测。
//
// 学 spec-kit 教训：tasks→issues 做成「可移除的能力」，不绑死在核心命令里；
// 真正发送交由宿主用 gh CLI / API 完成。

export type TaskLevel = 'S' | 'M' | 'L' | 'CRITICAL'

export interface TaskInput {
  id: string
  title: string
  description?: string
  level?: TaskLevel
  filesInvolved?: string[]
}

export interface IssueDraft {
  taskId: string
  title: string
  body: string
  labels: string[]
}

export interface IssuePlan {
  repoNote: string
  issues: IssueDraft[]
  dryRun: true
}

const LEVEL_LABEL: Record<TaskLevel, string> = {
  S: 'scale:level-s',
  M: 'scale:level-m',
  L: 'scale:level-l',
  CRITICAL: 'scale:level-critical',
}

function renderBody(task: TaskInput): string {
  const lines = [
    `<!-- generated by scale github plan-issues from task ${task.id} -->`,
    '',
    task.description ?? task.title,
    '',
  ]
  if (task.filesInvolved && task.filesInvolved.length > 0) {
    lines.push('### Files involved', ...task.filesInvolved.map(f => `- \`${f}\``), '')
  }
  lines.push(
    '### Verification (SCALE)',
    '- Run the configured verification: `scale verify-task --effort --json`',
    '- For L/CRITICAL: `scale review --isolated --fresh-gate block --json`',
    '- Attach command evidence; do not claim done without output.',
  )
  return lines.join('\n')
}

export function planIssues(tasks: TaskInput[], repo = '<owner/repo>'): IssuePlan {
  const issues: IssueDraft[] = tasks.map(task => {
    const labels = ['scale', 'task']
    if (task.level) labels.push(LEVEL_LABEL[task.level])
    return {
      taskId: task.id,
      title: `[${task.id}] ${task.title}`.slice(0, 250),
      body: renderBody(task),
      labels,
    }
  })
  return {
    repoNote: `Dry run — no issues created. To publish: gh issue create --repo ${repo} --title ... --body ... --label ...`,
    issues,
    dryRun: true,
  }
}
